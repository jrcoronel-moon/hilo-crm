-- name: ArchiveCompany :execrows
UPDATE companies SET archived_at = now(), updated_at = now() WHERE workspace_id = $1 AND id = $2 AND archived_at IS NULL;

-- name: ListCompanies :many
SELECT * FROM companies
WHERE workspace_id = $1 AND archived_at IS NULL
  AND (sqlc.narg(query)::text IS NULL OR name ILIKE '%' || sqlc.narg(query) || '%' OR domain ILIKE '%' || sqlc.narg(query) || '%')
  AND (sqlc.narg(owner_id)::uuid IS NULL OR owner_id = sqlc.narg(owner_id))
  AND (sqlc.narg(tag)::text IS NULL OR sqlc.narg(tag) = ANY (tags))
  AND (sqlc.narg(cursor)::uuid IS NULL OR id < sqlc.narg(cursor))
ORDER BY id DESC
LIMIT sqlc.arg(lim);

