-- Timeline of one record: interactions and stage changes, newest first.
-- name: Timeline :many
SELECT 'interaction'::text AS kind, i.id, i.occurred_at AS at, i.type AS label, i.direction AS detail,
       i.subject, i.summary, i.opportunity_id
FROM interactions i
WHERE i.workspace_id = sqlc.arg(workspace_id)
  AND ((sqlc.narg(opportunity_id)::uuid IS NOT NULL AND i.opportunity_id = sqlc.narg(opportunity_id))
    OR (sqlc.narg(contact_id)::uuid IS NOT NULL AND i.contact_id = sqlc.narg(contact_id))
    OR (sqlc.narg(company_id)::uuid IS NOT NULL AND i.company_id = sqlc.narg(company_id)))
UNION ALL
SELECT 'stage_change'::text, sc.id, sc.changed_at, sc.to_stage_name, sc.to_category,
       sc.from_stage_name, sc.reason, sc.opportunity_id
FROM stage_changes sc
JOIN opportunities o ON o.id = sc.opportunity_id
WHERE sc.workspace_id = sqlc.arg(workspace_id)
  AND ((sqlc.narg(opportunity_id)::uuid IS NOT NULL AND sc.opportunity_id = sqlc.narg(opportunity_id))
    OR (sqlc.narg(contact_id)::uuid IS NOT NULL AND o.primary_contact_id = sqlc.narg(contact_id))
    OR (sqlc.narg(company_id)::uuid IS NOT NULL AND o.company_id = sqlc.narg(company_id)))
ORDER BY at DESC
LIMIT sqlc.arg(lim);

