-- name: Search :many
(SELECT 'company'::text AS type, id, name AS title, COALESCE(domain, '') AS subtitle
   FROM companies
  WHERE companies.workspace_id = sqlc.arg(workspace_id) AND archived_at IS NULL
    AND (name ILIKE '%' || sqlc.arg(query)::text || '%' OR domain ILIKE '%' || sqlc.arg(query)::text || '%')
  LIMIT sqlc.arg(lim))
UNION ALL
(SELECT 'contact', id, trim(first_name || ' ' || last_name), COALESCE(email, '')
   FROM contacts
  WHERE contacts.workspace_id = sqlc.arg(workspace_id) AND archived_at IS NULL
    AND ((first_name || ' ' || last_name) ILIKE '%' || sqlc.arg(query)::text || '%' OR email ILIKE '%' || sqlc.arg(query)::text || '%')
  LIMIT sqlc.arg(lim))
UNION ALL
(SELECT 'opportunity', id, title, status
   FROM opportunities
  WHERE opportunities.workspace_id = sqlc.arg(workspace_id) AND archived_at IS NULL
    AND title ILIKE '%' || sqlc.arg(query)::text || '%'
  LIMIT sqlc.arg(lim));
